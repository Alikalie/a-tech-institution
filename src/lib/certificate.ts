import { brandFrame, documentColors, loadBrandLogo } from "@/lib/document-brand";
import type { CertificateValues } from "./certificate-rules";
export type { CertificateValues } from "./certificate-rules";
export async function downloadCertificate(values: CertificateValues) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "landscape", format: "a4" });
  brandFrame(doc, "Certificate", "OF ACHIEVEMENT");
  const logo = await loadBrandLogo();
  doc.setFillColor(...documentColors.deep);
  doc.rect(24, 46, 32, 153, "F");
  doc.setDrawColor(...documentColors.yellow);
  doc.setLineWidth(1.5);
  doc.line(24, 46, 24, 198);
  doc.line(56, 46, 56, 198);
  doc.setFillColor(...documentColors.yellow);
  doc.circle(40, 96, 26, "F");
  doc.setDrawColor(...documentColors.deep);
  doc.setLineWidth(0.6);
  doc.circle(40, 96, 23, "S");
  if (logo) doc.addImage(logo, "JPEG", 30, 76, 20, 20);
  doc.setTextColor(...documentColors.deep);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text("A-TECH", 40, 103, { align: "center" });
  doc.setFontSize(7);
  doc.text(["TRAINING", "COMPLETION"], 40, 110, { align: "center" });
  doc.setFontSize(12);
  doc.text(["THIS CERTIFICATE IS PROUDLY PRESENTED", "FOR ACHIEVEMENT TO"], 182, 61, { align: "center", lineHeightFactor: 1.4 });
  doc.setFont("times", "bolditalic");
  const nameSize = Math.min(32, 32 * 178 / Math.max(178, doc.getStringUnitWidth(values.fullName) * 32 * 0.3528));
  doc.setFontSize(nameSize);
  doc.text(values.fullName, 181, 93, { align: "center", maxWidth: 182 });
  doc.setLineWidth(0.5);
  doc.line(83, 99, 279, 99);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text("Successfully completed the A-TECH training programme in", 181, 111, { align: "center" });
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  const courseLines = doc.splitTextToSize(values.courseName, 180);
  doc.text(courseLines, 181, 121, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  const courseBottom = 121 + (courseLines.length - 1) * 5;
  doc.text(values.award || "Demonstrating commitment, dedication and excellence in the programme.", 181, courseBottom + 9, { align: "center", maxWidth: 180 });
  const date = (v: string) => new Date(`${v}T00:00:00`).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
  doc.setFont("helvetica", "bold");
  doc.text(`CONDUCTED FROM ${date(values.startDate)} TO ${date(values.endDate)}`, 181, courseBottom + 20, { align: "center" });
  doc.setFontSize(8);
  doc.text(`STUDENT ID: ${values.studentId || "—"}   |   DURATION: ${values.duration || "—"}`, 181, courseBottom + 27, { align: "center", maxWidth: 180 });
  doc.setFontSize(10);
  doc.line(87, 171, 141, 171);
  doc.line(224, 171, 277, 171);
  doc.text("DIRECTOR", 114, 179, { align: "center" });
  doc.text("H.O.D.", 251, 179, { align: "center" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.text(values.director || "A-TECH", 114, 185, { align: "center", maxWidth: 52 });
  doc.text(values.headOfDepartment || "A-TECH", 251, 185, { align: "center", maxWidth: 52 });
  doc.setDrawColor(...documentColors.blue);
  doc.circle(183, 173, 16, "S");
  doc.circle(183, 173, 14, "S");
  if (logo) doc.addImage(logo, "JPEG", 176, 166, 14, 14);
  doc.setFontSize(6);
  doc.text("A-TECH", 183, 164, { align: "center" });
  doc.text("TRAINING", 183, 184, { align: "center" });
  doc.setFontSize(8);
  doc.text(`CERTIFICATE NO: ${values.number}`, 85, 198);
  doc.text(`ISSUE DATE: ${date(values.issueDate)}`, 271, 198, { align: "right" });
  doc.save(`ATECH_Certificate_${values.number.replaceAll("/", "-")}.pdf`);
}